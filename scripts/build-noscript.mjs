// Regenerates the no-JS fallback card list in work/index.html from
// data/cases.js. Run: node scripts/build-noscript.mjs
//
// Why this exists: the fallback used to be hand-written HTML and drifted
// out of sync with the data repeatedly (a removed case left as a dead link,
// renamed titles, missing dates) before anyone noticed, because nothing
// forced it to stay in sync. Generating it from the same source the rest
// of the site reads from makes that class of bug structurally impossible
// instead of relying on someone remembering.
//
// index.html itself used to get the same treatment (a JS-built matrix/card
// list with a generated noscript fallback for when JS was off). The
// Coverage Matrix was retired and the new landing page is fully static
// HTML with no JS-only content, so there's no fallback/enhanced split left
// on that page to regenerate — see scripts/build-home.mjs for how its
// three featured cases are kept in sync with the data instead.
//
// The ordering logic here (most recent first) is duplicated from
// js/render-work.js rather than imported — that module calls init()
// against `document` at load time, which would throw in Node. Keep the
// two in sync if the ordering rule ever changes.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CAPABILITIES, LISTED_CASES } from '../data/cases.js';
import { displayLabel, displayDateRange } from '../js/case-utils.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const capabilityLabel = new Map(CAPABILITIES.map((c) => [c.slug, c.label]));

function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function cardHtml(caseObj) {
  const dateText = displayDateRange(caseObj);
  const org = dateText ? `${displayLabel(caseObj)} · ${dateText}` : displayLabel(caseObj);
  const tags = caseObj.capabilities.map((s) => `<li>${escapeHtml(capabilityLabel.get(s))}</li>`).join('');
  return `      <a class="case-card" href="${caseObj.slug}/">
        <p class="card-title">${escapeHtml(caseObj.title)}</p>
        <p class="card-org">${escapeHtml(org)}</p>
        <ul class="card-tags">${tags}</ul>
      </a>`;
}

function replaceBetweenMarkers(html, start, end, replacement, label) {
  const startIdx = html.indexOf(start);
  const endIdx = html.indexOf(end);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`${label} markers not found — did the file structure change?`);
  }
  const before = html.slice(0, startIdx + start.length);
  const after = html.slice(endIdx);
  return `${before}\n${replacement}\n      ${after}`;
}

// work/index.html: flat list, P0 first then most recent — must match
// js/render-work.js's orderForWork exactly.
function recencyKey(caseObj) {
  return caseObj.dateEnd || caseObj.dateStart || null;
}

// Most recent first. PRD v2 dropped v1's P0/P1 launch-list distinction,
// so recency is the whole ordering now.
function orderForWork(cases) {
  return [...cases].sort((a, b) => {
    const ka = recencyKey(a);
    const kb = recencyKey(b);
    if (ka === null && kb === null) return 0;
    if (ka === null) return 1;
    if (kb === null) return -1;
    return kb.localeCompare(ka);
  });
}

function buildWorkList() {
  return orderForWork(LISTED_CASES).map(cardHtml).join('\n');
}

function run() {
  const workPath = join(ROOT, 'work', 'index.html');
  const workHtml = readFileSync(workPath, 'utf8');
  const workUpdated = replaceBetweenMarkers(
    workHtml,
    '<!-- NOSCRIPT-WORK:START — generated by scripts/build-noscript.mjs, do not hand-edit -->',
    '<!-- NOSCRIPT-WORK:END -->',
    buildWorkList(),
    'work/index.html NOSCRIPT-WORK'
  );
  writeFileSync(workPath, workUpdated);

  console.log(`Regenerated no-JS fallback: work/index.html (${LISTED_CASES.length} listed cases, most recent first).`);
}

run();
